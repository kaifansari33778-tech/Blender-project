def cut(parts, w, h, col, seed=0, rim=4, shade=True): return _blob(w, h, parts, col, seed, rim, shade)[0]


def paint(spr, parts, col):
    """Paint extra flat shapes onto an existing cut-out (0..1 units)."""
    h, w = spr.shape[:2]
    for p in parts:
        c = tuple(float(v) for v in col) + (1.0,)
        if p[0] == 'e': cv2.ellipse(spr, (int(p[1] * w), int(p[2] * h)), (int(p[3] * w), int(p[4] * h)), 0, 0, 360, c, -1, cv2.LINE_AA)
        elif p[0] == 'l': cv2.line(spr, (int(p[1] * w), int(p[2] * h)), (int(p[3] * w), int(p[4] * h)), c, p[5], cv2.LINE_AA)
        else: cv2.fillPoly(spr, [np.int32([(x * w, y * h) for x, y in p[1]])], c, cv2.LINE_AA)
    return spr


