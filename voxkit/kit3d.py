def bridge(w=2600, h=900):
    col = (.72, .22, .14); s = np.zeros((h, w, 4), np.float32); c = col + (1.0,)
    for x in (.3, .7):
        cv2.rectangle(s, (int(w * x) - 30, int(h * .08)), (int(w * x) + 30, h), c, -1)
        for y in (.2, .36, .52): cv2.rectangle(s, (int(w * x) - 44, int(h * y)), (int(w * x) + 44, int(h * y) + 24), c, -1)
    cv2.rectangle(s, (0, int(h * .7)), (w, int(h * .7) + 36), c, -1)
    xs = np.linspace(0, w, 200)
    def cable(x):
        u = x / w
        if u < .3: return h * (.7 - (.62) * (u / .3) ** 2)
        if u > .7: return h * (.7 - (.62) * ((1 - u) / .3) ** 2)
        return h * (.08 + .58 * (1 - ((u - .5) / .2) ** 2))
    pts = np.int32([(x, cable(x)) for x in xs]); cv2.polylines(s, [pts], False, c, 12, cv2.LINE_AA)
    for x in xs[::4]: cv2.line(s, (int(x), int(cable(x))), (int(x), int(h * .7)), c, 3, cv2.LINE_AA)
    s[..., :3] *= (0.85 + 0.3 * fbm(h, w, 20, 3, 5))[..., None]; return s


