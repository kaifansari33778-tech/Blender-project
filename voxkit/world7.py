def star_badge(s=300):
    b = np.zeros((s, s, 4), np.float32); c = s / 2; R = s * .44
    for a0 in (-math.pi / 2, math.pi / 2): cv2.fillPoly(b, [np.int32([(c + R * math.cos(a0 + i * 2.094), c + R * math.sin(a0 + i * 2.094)) for i in range(3)])], (.93, .78, .20, 1.0), cv2.LINE_AA)
    b[..., :3] *= (0.85 + 0.3 * fbm(s, s, 20, 3, 3))[..., None]
