    s = cut([('p', [(.04, rh), (.96, rh), (.96, 1), (.04, 1)]), ('p', [(0, rh + .02), (.5, 0), (1, rh + .02)])], w, h, [(.80, .72, .56), (.74, .66, .52), (.84, .76, .62)][seed % 3], 240 + seed)
