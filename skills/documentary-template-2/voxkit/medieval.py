def smoke(seed=0, w=420, h=900):
    r = np.random.default_rng(seed); m = np.zeros((h, w), np.float32)
    for i in range(12):
        k = i / 11; cv2.circle(m, (int(w * (.5 + .22 * math.sin(k * 5 + seed)) ), int(h * (1 - k * .95))), int(w * (.1 + .22 * k)), 1.0, -1, cv2.LINE_AA)
    return rgba(paper(h, w, np.float32([.20, .17, .16]), seed, .04, .1), cv2.GaussianBlur(m, (0, 0), 14) * .6 * np.linspace(.3, 1, h, dtype=np.float32)[:, None])


